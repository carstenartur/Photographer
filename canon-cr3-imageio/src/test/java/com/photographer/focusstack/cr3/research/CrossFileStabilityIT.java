/**
 * Work-package 2 (Update s) — cross-file / burst-like stability audit.
 *
 * <p>Computes stability metrics on header (CMP1, IAD1, CTBO), preview, thumbnail, 
 * tile, and plane level across the 3 EOS R triade, 5 G5 X II lossless series, 
 * and the 2-frame C-RAW burst. Documents which quantities stay stable across 
 * near-frames and which don't.</p>
 *
 * <p>Outputs TSV to {@code target/cross-file-stability/stability.tsv}.</p>
 */
class CrossFileStabilityIT {

    private static final Logger log = LoggerFactory.getLogger(CrossFileStabilityIT.class);

    private static final Path SAMPLES_DIR  = Path.of("src", "test", "resources", "samples");
    private static final Path RESEARCH_DIR = SAMPLES_DIR.resolve("research");
    private static final Path REPORT_DIR   = Path.of("target", "cross-file-stability");

    @Test
    @DisplayName("Cross-file stability metrics for EOS R triade, G5XII series, and C-RAW burst")
    void emitCrossFileStabilityReport() throws Exception {
        if (!Files.isDirectory(SAMPLES_DIR)) {
            log.info("No samples dir — skip");
            return;
        }
        List<Path> all = new ArrayList<>();
        collect(SAMPLES_DIR, all);
        if (Files.isDirectory(RESEARCH_DIR)) collect(RESEARCH_DIR, all);
        all.sort(Comparator.comparing(Path::toString));
        if (all.isEmpty()) {
            log.info("No CR3 fixtures — skip");
            return;
        }

        // Parse all fixtures into records
        List<FileRecord> records = new ArrayList<>();
        for (Path p : all) {
            try {
                records.add(parse(p));
            } catch (Exception e) {
                log.warn("Skipped {}: {}", p.getFileName(), e.toString());
            }
        }

        // Group by camera and series
        Map<String, List<FileRecord>> eosrGroup = new LinkedHashMap<>();
        Map<String, List<FileRecord>> g5xm2Lossless = new LinkedHashMap<>();
        Map<String, List<FileRecord>> crawBurst = new LinkedHashMap<>();

        for (FileRecord r : records) {
            if (r.camera.equals("eosr") && r.waveletLevels == 0) {
                eosrGroup.computeIfAbsent("eosr-triade", k -> new ArrayList<>()).add(r);
            }
            if (r.camera.equals("g5xm2") && r.waveletLevels == 0) {
                g5xm2Lossless.computeIfAbsent("g5xm2-lossless", k -> new ArrayList<>()).add(r);
            }
            if (r.waveletLevels > 0) {
                crawBurst.computeIfAbsent(r.burstKey, k -> new ArrayList<>()).add(r);
            }
        }

        Files.createDirectories(REPORT_DIR);
        Path tsv = REPORT_DIR.resolve("stability.tsv");
        Path md = REPORT_DIR.resolve("stability.md");

        try (var out = Files.newBufferedWriter(tsv);
             var doc = Files.newBufferedWriter(md)) {
            out.write("groupName\tgroupType\tfileCount\tfield\tvalueDistinct\tvalueList\tstableAcrossGroup\n");

            doc.write("# Cross-File Stability Audit (Update s)\n\n");
            doc.write("Generated by `CrossFileStabilityIT`. Examines header/metadata stability.\n\n");

            // EOS R triade
            for (var e : eosrGroup.entrySet()) {
                writeGroupAnalysis(out, doc, e.getKey(), "eosr-triade", e.getValue());
            }

            // G5 X II lossless series
            for (var e : g5xm2Lossless.entrySet()) {
                writeGroupAnalysis(out, doc, e.getKey(), "g5xm2-lossless", e.getValue());
            }

            // C-RAW burst pairs
            for (var e : crawBurst.entrySet()) {
                if (e.getValue().size() >= 2) {
                    writeGroupAnalysis(out, doc, e.getKey(), "craw-burst", e.getValue());
                }
            }

            doc.write("\n## Summary\n\n");
            doc.write("- **EOS R triade:** " + eosrGroup.values().stream().mapToInt(List::size).sum() + " files\n");
            doc.write("- **G5 X II lossless:** " + g5xm2Lossless.values().stream().mapToInt(List::size).sum() + " files\n");
            doc.write("- **C-RAW burst pairs:** " + crawBurst.values().stream().filter(l -> l.size() >= 2).count() + " groups\n");
        }

        log.info("Wrote {} and {}", tsv.toAbsolutePath(), md.toAbsolutePath());
    }

    private void writeGroupAnalysis(java.io.BufferedWriter out, java.io.BufferedWriter doc,
                                    String groupName, String groupType, List<FileRecord> files) throws java.io.IOException {
        if (files.isEmpty()) return;

        doc.write("\n## Group: " + groupName + " (" + groupType + ", " + files.size() + " files)\n\n");
        doc.write("| Field | Distinct | Values | Stable? |\n");
        doc.write("|-------|----------|--------|--------|\n");

        // Analyze stability of each field
        analyzeField(out, doc, groupName, groupType, files, "cmp1.imageWidth", r -> String.valueOf(r.imageWidth));
        analyzeField(out, doc, groupName, groupType, files, "cmp1.imageHeight", r -> String.valueOf(r.imageHeight));
        analyzeField(out, doc, groupName, groupType, files, "cmp1.tileWidth", r -> String.valueOf(r.tileWidth));
        analyzeField(out, doc, groupName, groupType, files, "cmp1.tileHeight", r -> String.valueOf(r.tileHeight));
        analyzeField(out, doc, groupName, groupType, files, "cmp1.bitsPerSample", r -> String.valueOf(r.bitsPerSample));
        analyzeField(out, doc, groupName, groupType, files, "cmp1.numPlanes", r -> String.valueOf(r.numPlanes));
        analyzeField(out, doc, groupName, groupType, files, "cmp1.cfaLayout", r -> String.valueOf(r.cfaLayout));
        analyzeField(out, doc, groupName, groupType, files, "cmp1.waveletLevels", r -> String.valueOf(r.waveletLevels));
        analyzeField(out, doc, groupName, groupType, files, "cmp1.mdatHeaderSize", r -> String.valueOf(r.mdatHeaderSize));
        analyzeField(out, doc, groupName, groupType, files, "iad1.leftObRect", r -> r.leftObRect);
        analyzeField(out, doc, groupName, groupType, files, "iad1.topObRect", r -> r.topObRect);
        analyzeField(out, doc, groupName, groupType, files, "iad1.activeArea", r -> r.activeArea);
        analyzeField(out, doc, groupName, groupType, files, "prvw.size", r -> r.prvwSize);
        analyzeField(out, doc, groupName, groupType, files, "thmb.size", r -> r.thmbSize);
        analyzeField(out, doc, groupName, groupType, files, "tiles.count", r -> String.valueOf(r.tileCount));
        analyzeField(out, doc, groupName, groupType, files, "subbands.quantValues", r -> r.quantValues);
        analyzeField(out, doc, groupName, groupType, files, "plane0.encodedBytes", r -> String.valueOf(r.plane0Bytes));
        analyzeField(out, doc, groupName, groupType, files, "plane1.encodedBytes", r -> String.valueOf(r.plane1Bytes));
        analyzeField(out, doc, groupName, groupType, files, "plane2.encodedBytes", r -> String.valueOf(r.plane2Bytes));
        analyzeField(out, doc, groupName, groupType, files, "plane3.encodedBytes", r -> String.valueOf(r.plane3Bytes));
        analyzeField(out, doc, groupName, groupType, files, "tile0.encodedBytes", r -> String.valueOf(r.tile0Bytes));
        analyzeField(out, doc, groupName, groupType, files, "tile1.encodedBytes", r -> String.valueOf(r.tile1Bytes));
    }

    private void analyzeField(java.io.BufferedWriter out, java.io.BufferedWriter doc,
                              String groupName, String groupType, List<FileRecord> files,
                              String fieldName, java.util.function.Function<FileRecord, String> extractor) throws java.io.IOException {
        Set<String> distinct = new TreeSet<>();
        List<String> values = new ArrayList<>();
        for (FileRecord r : files) {
            String v = extractor.apply(r);
            distinct.add(v);
            values.add(v);
        }
        boolean stable = distinct.size() == 1;
        String valueList = distinct.size() <= 5 ? String.join(",", distinct) : distinct.size() + " values";
        
        out.write(String.format("%s\t%s\t%d\t%s\t%d\t%s\t%s%n",
                groupName, groupType, files.size(), fieldName, distinct.size(), valueList, stable ? "YES" : "NO"));
        doc.write(String.format("| %s | %d | %s | %s |\n",
                fieldName, distinct.size(), valueList, stable ? "✓" : "✗"));
        
        if (stable) {
            log.info("  {} [{}]: {} = {} (STABLE across {} files)",
                    groupName, groupType, fieldName, distinct.iterator().next(), files.size());
        } else {
            log.info("  {} [{}]: {} = {} distinct values (VARIES)",
                    groupName, groupType, fieldName, distinct.size());
        }
    }

    private static void collect(Path dir, List<Path> out) throws java.io.IOException {
        try (Stream<Path> s = Files.list(dir)) {
            s.filter(Files::isRegularFile)
             .filter(p -> p.getFileName().toString().toLowerCase().endsWith(".cr3"))
             .forEach(out::add);
        }
    }

    private FileRecord parse(Path file) throws Exception {
        FileRecord r = new FileRecord();
        r.filename = file.getFileName().toString();
        String n = r.filename.toLowerCase();
        r.camera = n.startsWith("eosr") ? "eosr" : (n.startsWith("g5xm2") || n.startsWith("sample")) ? "g5xm2" : "?";
        
        // Derive burst key from filename
        java.util.regex.Matcher m = java.util.regex.Pattern
                .compile("^(.*)-(\\d{8}-\\d{6})-(\\d{2})\\.cr3$", java.util.regex.Pattern.CASE_INSENSITIVE).matcher(r.filename);
        r.burstKey = m.matches() ? m.group(1) + "|" + m.group(2) : r.filename + "|solo";

        try (ImageInputStream in = ImageIO.createImageInputStream(file.toFile())) {
            Cr3Container c = Cr3Parser.parse(in);

            PrvwBox prvw = c.prvwBox();
            ThmbBox thmb = c.thmbBox();
            r.prvwSize = prvw == null ? "-" : prvw.width() + "x" + prvw.height();
            r.thmbSize = thmb == null ? "-" : thmb.width() + "x" + thmb.height();

            Cr3Track raw = c.tracks().stream()
                    .filter(t -> t.type() == Cr3Track.TrackType.CRX_BIG || t.type() == Cr3Track.TrackType.CRX_RAW)
                    .findFirst().orElse(null);
            if (raw == null) return r;

            Cmp1Box cmp1 = raw.cmp1();
            if (cmp1 != null) {
                r.imageWidth = cmp1.imageWidth();
                r.imageHeight = cmp1.imageHeight();
                r.tileWidth = cmp1.tileWidth();
                r.tileHeight = cmp1.tileHeight();
                r.bitsPerSample = cmp1.bitsPerSample();
                r.numPlanes = cmp1.numPlanes();
                r.cfaLayout = cmp1.cfaLayout();
                r.waveletLevels = cmp1.waveletLevels();
                r.mdatHeaderSize = cmp1.mdatHeaderSize();
            }

            Iad1Box iad1 = raw.iad1();
            if (iad1 != null) {
                r.leftObRect = String.format("%d,%d,%d,%d", iad1.leftObLeft(), iad1.leftObTop(), iad1.leftObRight(), iad1.leftObBottom());
                r.topObRect = String.format("%d,%d,%d,%d", iad1.topObLeft(), iad1.topObTop(), iad1.topObRight(), iad1.topObBottom());
                r.activeArea = String.format("%d,%d,%d,%d", iad1.activeLeft(), iad1.activeTop(), iad1.activeRight(), iad1.activeBottom());
            }

            // Parse CRX header for tile/plane metrics
            try {
                byte[] head = new byte[(int) Math.min(raw.dataSize(), 16384L)];
                in.seek(raw.dataOffset());
                in.readFully(head);
                CrxHeader.CodecVersion ver = c.cncvBox() == null
                        ? CrxHeader.CodecVersion.V1
                        : CrxHeader.detectVersion(c.cncvBox().versionString());
                CrxHeader hdr = CrxHeader.parse(head, ver);
                
                r.tileCount = hdr.tiles().size();
                Set<Integer> qs = new TreeSet<>();
                long[] planeBytes = new long[4];
                long[] tileBytes = new long[2];
                
                int tileIdx = 0;
                for (var tile : hdr.tiles()) {
                    if (tileIdx < 2) tileBytes[tileIdx] = tile.dataSize();
                    int planeIdx = 0;
                    for (var plane : tile.planes()) {
                        if (tileIdx == 0 && planeIdx < 4) planeBytes[planeIdx] = plane.dataSize();
                        for (var sb : plane.subbands()) {
                            qs.add(sb.quantValue());
                        }
                        planeIdx++;
                    }
                    tileIdx++;
                }
                r.quantValues = qs.toString();
                r.plane0Bytes = planeBytes[0];
                r.plane1Bytes = planeBytes[1];
                r.plane2Bytes = planeBytes[2];
                r.plane3Bytes = planeBytes[3];
                r.tile0Bytes = tileBytes[0];
                r.tile1Bytes = tileBytes.length > 1 ? tileBytes[1] : 0;
            } catch (Exception e) {
                log.debug("CRX header parse failed for {}: {}", r.filename, e.toString());
            }
        }
        return r;
    }

    private static class FileRecord {
        String filename = "?";
        String camera = "?";
        String burstKey = "?";
        int imageWidth, imageHeight;
        int tileWidth, tileHeight;
        int bitsPerSample, numPlanes, cfaLayout, waveletLevels, mdatHeaderSize;
        String leftObRect = "-", topObRect = "-", activeArea = "-";
        String prvwSize = "-", thmbSize = "-";
        int tileCount;
        String quantValues = "[]";
        long plane0Bytes, plane1Bytes, plane2Bytes, plane3Bytes;
        long tile0Bytes, tile1Bytes;
    }
}
