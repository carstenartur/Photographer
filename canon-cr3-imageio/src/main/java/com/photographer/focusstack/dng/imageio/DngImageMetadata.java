package com.photographer.focusstack.dng.imageio;

import com.photographer.focusstack.cr3.imageio.Cr3ImageMetadata;
import java.awt.Image;
import java.awt.image.BufferedImage;
import java.util.Hashtable;
import java.util.Objects;
import java.util.Set;
import javax.imageio.IIOException;
import javax.imageio.metadata.IIOMetadata;
import javax.imageio.metadata.IIOMetadataFormat;
import javax.imageio.plugins.tiff.TIFFDirectory;
import javax.imageio.plugins.tiff.TIFFField;
import javax.imageio.plugins.tiff.TIFFTag;
import org.w3c.dom.Node;

/**
 * Sensor geometry and calibration for an uncompressed 16-bit RGB Bayer Digital Negative.
 * The directory describes the full sensor mosaic, including any masked margins.
 * This product includes DNG technology under license by Adobe.
 */
public final class DngImageMetadata extends IIOMetadata {
    /** Property used by ImageIO.write to carry raw calibration alongside the sensor raster. */
    public static final String PROPERTY_NAME = "com.photographer.focusstack.dng.metadata";
    /** Native TIFF image metadata tree. */
    public static final String NATIVE_FORMAT_NAME = "javax_imageio_tiff_image_1.0";

    // Copy self-contained fields relevant to RAW development. Other IFDs and file offsets
    // belong to the source file, and strip/tile locations are generated by the TIFF writer.
    private static final Set<Integer> COPY_TAGS = Set.of(
            254, 256, 257, 258, 259, 262, 270, 271, 272, 274, 277, 282, 283, 284,
            296, 305, 306, 315, 33432, 339, 700, 33421, 33422, 50706, 50707, 50708,
            50709, 50710, 50711, 50712, 50713, 50714, 50715, 50716, 50717, 50718,
            50719, 50720, 50721, 50722, 50723, 50724, 50727, 50728, 50729, 50730,
            50731, 50732, 50733, 50734, 50735, 50736, 50738, 50778, 50779, 50829,
            50830, 50931, 50932, 50936, 50937, 50938, 50939, 50940, 50941, 50942,
            50964, 50965, 50981, 50982, 51008, 51009, 51022, 51041, 51107, 51108,
            51109, 51110);
    private final TIFFDirectory directory;

    private DngImageMetadata(TIFFDirectory directory) {
        super(false, NATIVE_FORMAT_NAME, null, null, null);
        this.directory = directory;
    }

    /** Creates metadata from a DNG RAW IFD with an RGB Bayer mosaic and camera color calibration. */
    public static DngImageMetadata fromDirectory(TIFFDirectory source) throws IIOException {
        Objects.requireNonNull(source, "source");
        try {
            TIFFField version = required(source, 50706, 4);
            if (version.getType() != TIFFTag.TIFF_BYTE || version.getAsInt(0) != 1) {
                throw new IIOException("Unsupported DNGVersion");
            }
            int width = dimension(source, 256);
            int height = dimension(source, 257);
            if (required(source, 262, 1).getAsInt(0) != 32803 || required(source, 258, 1).getAsInt(0) != 16
                    || scalar(source, 277, 1) != 1 || scalar(source, 339, 1) != 1
                    || scalar(source, 259, 1) != 1 || scalar(source, 50711, 1) != 1) {
                throw new IIOException("Expected an uncompressed single-band unsigned 16-bit rectangular CFA mosaic");
            }
            checkBayer(source);
            if (required(source, 50708, 1).getAsString(0).isBlank()) {
                throw new IIOException("Missing DNG camera model");
            }
            TIFFField matrix = required(source, 50721, 9);
            if (matrix.getType() != TIFFTag.TIFF_SRATIONAL) {
                throw new IIOException("ColorMatrix1 must contain nine signed rationals");
            }
            for (int i = 0; i < 9; i++) {
                if (!Double.isFinite(matrix.getAsDouble(i))) {
                    throw new IIOException("Non-finite DNG ColorMatrix1 coefficient");
                }
            }
            checkLevels(source, width, height);
            TIFFField area = source.getTIFFField(50829);
            if (area != null) {
                required(source, 50829, 4);
                long top = area.getAsLong(0), left = area.getAsLong(1);
                long bottom = area.getAsLong(2), right = area.getAsLong(3);
                if (left < 0 || top < 0 || right <= left || bottom <= top || right > width || bottom > height) {
                    throw new IIOException("DNG ActiveArea is outside the sensor");
                }
            }
            int orientation = scalar(source, 274, 1);
            if (orientation < 1 || orientation > 8) {
                throw new IIOException("Invalid DNG orientation");
            }
            TIFFDirectory copy = copyFields(source);
            copy.addTIFFField(DngTags.shorts(274, orientation));
            copy.addTIFFField(DngTags.longs(254, 0));
            return new DngImageMetadata(copy);
        } catch (IllegalArgumentException | IndexOutOfBoundsException | ClassCastException ex) {
            throw new IIOException("Invalid DNG sensor metadata", ex);
        }
    }

    /** Converts calibration and geometry from a supported CR3 camera. */
    public static DngImageMetadata fromCr3(Cr3ImageMetadata metadata) throws IIOException {
        return fromDirectory(Cr3DngMetadata.fromCr3(metadata));
    }

    private static void checkLevels(TIFFDirectory dir, int width, int height) throws IIOException {
        long white = dir.containsTIFFField(50717) ? required(dir, 50717, 1).getAsLong(0) : 65535;
        if (white < 1 || white > 65535) {
            throw new IIOException("WhiteLevel is outside the 16-bit sample range");
        }
        TIFFField black = dir.getTIFFField(50714);
        if (black != null) {
            int rows = 1, columns = 1;
            if (dir.containsTIFFField(50713)) {
                TIFFField period = required(dir, 50713, 2);
                rows = period.getAsInt(0);
                columns = period.getAsInt(1);
            }
            if (rows < 1 || columns < 1 || rows > height || columns > width
                    || (long) rows * columns != black.getCount()) {
                throw new IIOException("BlackLevel dimensions do not match BlackLevelRepeatDim");
            }
            for (int i = 0; i < black.getCount(); i++) {
                double value = black.getAsDouble(i);
                if (!Double.isFinite(value) || value < 0 || value >= white) {
                    throw new IIOException("BlackLevel must be below WhiteLevel");
                }
            }
        }
    }

    private static void checkBayer(TIFFDirectory dir) throws IIOException {
        TIFFField repeat = required(dir, 33421, 2);
        if (repeat.getAsInt(0) != 2 || repeat.getAsInt(1) != 2) {
            throw new IIOException("Expected a 2 by 2 Bayer mosaic");
        }
        TIFFField cfa = required(dir, 33422, 4);
        TIFFField planes = dir.containsTIFFField(50710) ? required(dir, 50710, 3) : null;
        int[] sites = new int[4];
        int[] counts = new int[3];
        for (int i = 0; i < sites.length; i++) {
            int plane = cfa.getAsInt(i);
            sites[i] = planes == null ? plane : planes.getAsInt(plane);
            counts[sites[i]]++;
        }
        if (counts[0] != 1 || counts[1] != 2 || counts[2] != 1
                || (sites[0] != sites[3] && sites[1] != sites[2])) {
            throw new IIOException("Expected an RGB Bayer pattern with diagonally opposite green sites");
        }
    }

    private static int dimension(TIFFDirectory dir, int tag) throws IIOException {
        long value = required(dir, tag, 1).getAsLong(0);
        if (value <= 0 || value > Integer.MAX_VALUE) {
            throw new IIOException("Invalid DNG image dimension in tag " + tag);
        }
        return (int) value;
    }

    private static int scalar(TIFFDirectory dir, int tag, int defaultValue) throws IIOException {
        return dir.containsTIFFField(tag) ? required(dir, tag, 1).getAsInt(0) : defaultValue;
    }

    private static TIFFField required(TIFFDirectory dir, int tag, int count) throws IIOException {
        TIFFField field = dir.getTIFFField(tag);
        if (field == null || field.getCount() != count) {
            throw new IIOException("Expected " + count + " value(s) in DNG tag " + tag);
        }
        return field;
    }

    static boolean isCopiedTag(int number) {
        return COPY_TAGS.contains(number);
    }

    private static TIFFDirectory copyFields(TIFFDirectory source) {
        TIFFDirectory copy = DngTags.emptyDirectory();
        for (TIFFField field : source.getTIFFFields()) {
            if (isCopiedTag(field.getTagNumber()) && !field.hasDirectory()) {
                try {
                    TIFFField snapshot = field.clone();
                    // TIFFField.clone() copies only the outer array of a rational field.
                    if (field.getType() == TIFFTag.TIFF_RATIONAL) {
                        long[][] data = snapshot.getAsRationals();
                        for (int i = 0; i < data.length; i++) data[i] = data[i].clone();
                    } else if (field.getType() == TIFFTag.TIFF_SRATIONAL) {
                        int[][] data = snapshot.getAsSRationals();
                        for (int i = 0; i < data.length; i++) data[i] = data[i].clone();
                    }
                    copy.addTIFFField(snapshot);
                } catch (CloneNotSupportedException ex) {
                    throw new AssertionError(ex);
                }
            }
        }
        return copy;
    }

    /** Returns an independent directory suitable for the TIFF writer. */
    public TIFFDirectory toDirectory() {
        return copyFields(directory);
    }

    public int sensorWidth() { return directory.getTIFFField(256).getAsInt(0); }
    public int sensorHeight() { return directory.getTIFFField(257).getAsInt(0); }

    /** Adds the metadata property while sharing the full image's raster and preserving its other properties. */
    public static BufferedImage attach(BufferedImage image, IIOMetadata metadata) {
        Objects.requireNonNull(metadata, "metadata");
        var properties = new Hashtable<String, Object>();
        String[] names = image.getPropertyNames();
        if (names != null) {
            for (String name : names) {
                Object value = image.getProperty(name);
                if (value != Image.UndefinedProperty) {
                    properties.put(name, value);
                }
            }
        }
        properties.put(PROPERTY_NAME, metadata);
        return new BufferedImage(image.getColorModel(), image.getRaster(), image.isAlphaPremultiplied(), properties);
    }

    @Override public IIOMetadataFormat getMetadataFormat(String name) {
        return NATIVE_FORMAT_NAME.equals(name) ? DngImageReaderSpi.nativeFormat() : super.getMetadataFormat(name);
    }

    @Override public boolean isReadOnly() { return true; }
    @Override public Node getAsTree(String formatName) { return toDirectory().getAsMetadata().getAsTree(formatName); }
    @Override public void mergeTree(String formatName, Node tree) { throw new IllegalStateException("Read-only DNG metadata"); }
    @Override public void reset() { throw new IllegalStateException("Read-only DNG metadata"); }
}
