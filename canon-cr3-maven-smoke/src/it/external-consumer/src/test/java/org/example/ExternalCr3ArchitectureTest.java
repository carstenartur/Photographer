/**
 * Verifies the installed CR3 artifacts rather than parsing repository sources.
 *
 * <p>The external Maven consumer loads the exact JARs and POMs that a downstream
 * project resolves. The test therefore catches package moves, fully-qualified or
 * reflective class-name references, generated bytecode and dependency-graph
 * changes without relying on the repository working directory.</p>
 */
class ExternalCr3ArchitectureTest {

    private static final String GROUP_ID = "io.github.carstenartur";
    private static final String CR3_INTERNAL_PREFIX =
            "com/photographer/focusstack/cr3/";
    private static final String COMPATIBILITY_STATISTICS =
            CR3_INTERNAL_PREFIX + "research/SubbandStatistics";
    private static final Pattern CR3_INTERNAL_TYPE_REFERENCE = Pattern.compile(
            "com/photographer/focusstack/cr3/[A-Za-z0-9_$/]+");
    private static final Pattern CR3_DOTTED_TYPE_REFERENCE = Pattern.compile(
            "com\\.photographer\\.focusstack\\.cr3\\."
                    + "(?:[a-z][A-Za-z0-9_$]*\\.)*"
                    + "[A-Z_$][A-Za-z0-9_$]*(?:\\$[A-Za-z0-9_$]+)*");

    private static final List<ModuleContract> MODULES = List.of(
            new ModuleContract(
                    "cr3-container",
                    Cr3Parser.class,
                    EnumSet.of(Layer.CONTAINER),
                    EnumSet.of(Layer.CONTAINER),
                    Set.of()),
            new ModuleContract(
                    "cr3-metadata",
                    Cr3Metadata.class,
                    EnumSet.of(Layer.METADATA),
                    EnumSet.of(Layer.CONTAINER, Layer.METADATA),
                    Set.of()),
            new ModuleContract(
                    "cr3-codec",
                    BitReader.class,
                    EnumSet.of(Layer.CODEC),
                    EnumSet.of(Layer.CONTAINER, Layer.METADATA, Layer.CODEC),
                    Set.of(COMPATIBILITY_STATISTICS)),
            new ModuleContract(
                    "cr3-processing",
                    BlackLevelProcessor.class,
                    EnumSet.of(Layer.PROCESSING),
                    EnumSet.of(Layer.METADATA, Layer.CODEC, Layer.PROCESSING),
                    Set.of()),
            new ModuleContract(
                    "cr3-core",
                    Cr3Decoder.class,
                    EnumSet.of(Layer.CORE),
                    EnumSet.of(Layer.CONTAINER, Layer.METADATA, Layer.CODEC,
                            Layer.PROCESSING, Layer.CORE),
                    Set.of()),
            new ModuleContract(
                    "cr3-imageio",
                    CanonCr3ImageReader.class,
                    EnumSet.of(Layer.IMAGEIO),
                    EnumSet.of(Layer.CONTAINER, Layer.METADATA, Layer.CODEC,
                            Layer.PROCESSING, Layer.CORE, Layer.IMAGEIO),
                    Set.of())
    );

    private static final Map<String, Set<String>> EXPECTED_DIRECT_CR3_DEPENDENCIES = Map.of(
            "cr3-container", Set.of(),
            "cr3-metadata", Set.of("cr3-container"),
            "cr3-codec", Set.of("cr3-container", "cr3-metadata"),
            "cr3-processing", Set.of("cr3-metadata", "cr3-codec"),
            "cr3-core", Set.of(
                    "cr3-container", "cr3-metadata",
                    "cr3-codec", "cr3-processing"),
            "cr3-imageio", Set.of(
                    "cr3-container", "cr3-metadata",
                    "cr3-codec", "cr3-processing", "cr3-core")
    );

    @Test
    void installedPomsMatchTheAuthoritativeCr3DependencyGraph() throws Exception {
        Map<String, Set<String>> actual = new LinkedHashMap<>();
        for (ModuleContract module : MODULES) {
            Path pom = siblingPom(artifactJar(module.anchor()));
            actual.put(module.artifactId(), directRuntimeCr3Dependencies(pom));
        }

        assertEquals(EXPECTED_DIRECT_CR3_DEPENDENCIES, actual,
                "Installed CR3 POMs must preserve the documented acyclic dependency graph");
    }

    @Test
    void packagedClassesRespectArtifactOwnershipAndLayerDirection() throws Exception {
        List<String> violations = new ArrayList<>();
        Set<String> classesSeen = new HashSet<>();

        for (ModuleContract module : MODULES) {
            Path jarPath = artifactJar(module.anchor());
            try (JarFile jar = new JarFile(jarPath.toFile())) {
                List<JarEntry> classEntries = jar.stream()
                        .filter(entry -> !entry.isDirectory())
                        .filter(entry -> entry.getName().endsWith(".class"))
                        .filter(entry -> !entry.getName().startsWith("META-INF/versions/"))
                        .sorted(Comparator.comparing(JarEntry::getName))
                        .toList();

                for (JarEntry entry : classEntries) {
                    String sourceType = withoutClassSuffix(entry.getName());
                    if (!sourceType.startsWith(CR3_INTERNAL_PREFIX)) {
                        continue;
                    }
                    if (!classesSeen.add(sourceType)) {
                        violations.add("duplicate CR3 class across production artifacts: "
                                + sourceType);
                    }
                    verifyOwnership(module, sourceType, violations);
                    try (InputStream input = jar.getInputStream(entry)) {
                        verifyReferences(module, sourceType, input, violations);
                    }
                }
            }
        }

        assertTrue(violations.isEmpty(), () ->
                "Compiled CR3 artifact boundary violations:\n - "
                        + String.join("\n - ", violations));
    }

    private static void verifyOwnership(ModuleContract module, String type,
                                        List<String> violations) {
        if (isExplicitlyOwned(module, type)) {
            return;
        }
        Layer layer = layerOf(type);
        if (layer == null || !module.ownedLayers().contains(layer)) {
            violations.add(module.artifactId() + " contains class owned by "
                    + (layer == null ? "an unknown CR3 package" : layer)
                    + ": " + type);
        }
    }

    private static void verifyReferences(ModuleContract module, String sourceType,
                                         InputStream classFile,
                                         List<String> violations) throws IOException {
        for (String targetType : cr3TypeReferences(classFile)) {
            if (targetType.equals(sourceType) || isExplicitlyOwned(module, targetType)) {
                continue;
            }
            Layer targetLayer = layerOf(targetType);
            if (targetLayer == null) {
                violations.add(module.artifactId() + ": " + sourceType
                        + " references unknown CR3 package type " + targetType);
            } else if (!module.allowedReferenceLayers().contains(targetLayer)) {
                violations.add(module.artifactId() + ": " + sourceType
                        + " references forbidden " + targetLayer + " type " + targetType);
            }
        }
    }

    private static boolean isExplicitlyOwned(ModuleContract module, String type) {
        return module.explicitlyOwnedTypes().stream()
                .anyMatch(explicit -> type.equals(explicit)
                        || type.startsWith(explicit + "$"));
    }

    private static Set<String> cr3TypeReferences(InputStream classFile) throws IOException {
        try (DataInputStream input = new DataInputStream(
                new BufferedInputStream(classFile))) {
            int magic = input.readInt();
            if (magic != 0xCAFEBABE) {
                throw new IOException("Invalid class-file magic: 0x"
                        + Integer.toHexString(magic));
            }
            input.readUnsignedShort();
            input.readUnsignedShort();
            int constantPoolCount = input.readUnsignedShort();
            Set<String> references = new TreeSet<>();

            for (int index = 1; index < constantPoolCount; index++) {
                int tag = input.readUnsignedByte();
                switch (tag) {
                    case 1 -> collectReferences(input.readUTF(), references);
                    case 3, 4 -> input.skipNBytes(4);
                    case 5, 6 -> {
                        input.skipNBytes(8);
                        index++;
                    }
                    case 7, 8, 16, 19, 20 -> input.skipNBytes(2);
                    case 9, 10, 11, 12, 17, 18 -> input.skipNBytes(4);
                    case 15 -> input.skipNBytes(3);
                    default -> throw new IOException(
                            "Unsupported constant-pool tag " + tag);
                }
            }
            return references;
        }
    }

    private static void collectReferences(String value, Set<String> references) {
        Matcher internal = CR3_INTERNAL_TYPE_REFERENCE.matcher(value);
        while (internal.find()) {
            references.add(internal.group());
        }

        Matcher dotted = CR3_DOTTED_TYPE_REFERENCE.matcher(value);
        while (dotted.find()) {
            references.add(dotted.group().replace('.', '/'));
        }
    }

    private static Set<String> directRuntimeCr3Dependencies(Path pom) throws Exception {
        DocumentBuilderFactory factory = DocumentBuilderFactory.newInstance();
        factory.setNamespaceAware(true);
        factory.setXIncludeAware(false);
        factory.setExpandEntityReferences(false);
        factory.setFeature(XMLConstants.FEATURE_SECURE_PROCESSING, true);
        factory.setFeature("http://apache.org/xml/features/disallow-doctype-decl", true);
        factory.setFeature("http://xml.org/sax/features/external-general-entities", false);
        factory.setFeature("http://xml.org/sax/features/external-parameter-entities", false);
        factory.setAttribute(XMLConstants.ACCESS_EXTERNAL_DTD, "");
        factory.setAttribute(XMLConstants.ACCESS_EXTERNAL_SCHEMA, "");

        Element project = factory.newDocumentBuilder().parse(pom.toFile())
                .getDocumentElement();
        Element dependencies = directChild(project, "dependencies");
        if (dependencies == null) {
            return Set.of();
        }

        Set<String> result = new TreeSet<>();
        for (Element dependency : directChildren(dependencies, "dependency")) {
            String groupId = directChildText(dependency, "groupId");
            String artifactId = directChildText(dependency, "artifactId");
            String scope = directChildText(dependency, "scope");
            String optional = directChildText(dependency, "optional");
            if (!GROUP_ID.equals(groupId)
                    || artifactId == null
                    || "test".equals(scope)
                    || "provided".equals(scope)
                    || "true".equals(optional)) {
                continue;
            }
            result.add(artifactId);
        }
        return Set.copyOf(result);
    }

    private static Element directChild(Element parent, String localName) {
        for (Node child = parent.getFirstChild(); child != null;
             child = child.getNextSibling()) {
            if (child instanceof Element element
                    && localName.equals(element.getLocalName())) {
                return element;
            }
        }
        return null;
    }

    private static List<Element> directChildren(Element parent, String localName) {
        List<Element> result = new ArrayList<>();
        NodeList children = parent.getChildNodes();
        for (int index = 0; index < children.getLength(); index++) {
            Node child = children.item(index);
            if (child instanceof Element element
                    && localName.equals(element.getLocalName())) {
                result.add(element);
            }
        }
        return result;
    }

    private static String directChildText(Element parent, String localName) {
        Element child = directChild(parent, localName);
        if (child == null || child.getTextContent() == null
                || child.getTextContent().isBlank()) {
            return null;
        }
        return child.getTextContent().trim();
    }

    private static Path artifactJar(Class<?> anchor) throws Exception {
        URI location = Objects.requireNonNull(
                        anchor.getProtectionDomain().getCodeSource(),
                        "Missing code source for " + anchor.getName())
                .getLocation().toURI();
        Path path = Path.of(location).toAbsolutePath().normalize();
        assertTrue(Files.isRegularFile(path),
                () -> "Expected packaged dependency JAR for " + anchor.getName()
                        + ", got " + path);
        assertTrue(path.getFileName().toString().endsWith(".jar"),
                () -> "Expected JAR code source for " + anchor.getName()
                        + ", got " + path);
        return path;
    }

    private static Path siblingPom(Path jar) {
        String fileName = jar.getFileName().toString();
        Path pom = jar.resolveSibling(
                fileName.substring(0, fileName.length() - ".jar".length()) + ".pom");
        assertTrue(Files.isRegularFile(pom),
                () -> "Installed POM missing next to " + jar + ": " + pom);
        return pom;
    }

    private static String withoutClassSuffix(String value) {
        return value.substring(0, value.length() - ".class".length());
    }

    private static Layer layerOf(String internalType) {
        String remainder = internalType.startsWith(CR3_INTERNAL_PREFIX)
                ? internalType.substring(CR3_INTERNAL_PREFIX.length())
                : "";
        if (!remainder.isEmpty() && remainder.indexOf('/') < 0) {
            return Layer.CONTAINER;
        }
        if (internalType.startsWith(CR3_INTERNAL_PREFIX + "bmff/")
                || internalType.startsWith(CR3_INTERNAL_PREFIX + "container/")
                || internalType.startsWith(CR3_INTERNAL_PREFIX + "preview/")) {
            return Layer.CONTAINER;
        }
        if (internalType.startsWith(CR3_INTERNAL_PREFIX + "metadata/")) {
            return Layer.METADATA;
        }
        if (internalType.startsWith(CR3_INTERNAL_PREFIX + "raw/")) {
            return Layer.CODEC;
        }
        if (internalType.startsWith(CR3_INTERNAL_PREFIX + "processing/")) {
            return Layer.PROCESSING;
        }
        if (internalType.startsWith(CR3_INTERNAL_PREFIX + "decode/")
                || internalType.startsWith(CR3_INTERNAL_PREFIX + "encode/")) {
            return Layer.CORE;
        }
        if (internalType.startsWith(CR3_INTERNAL_PREFIX + "imageio/")) {
            return Layer.IMAGEIO;
        }
        if (internalType.startsWith(CR3_INTERNAL_PREFIX + "cli/")) {
            return Layer.CLI;
        }
        if (internalType.startsWith(CR3_INTERNAL_PREFIX + "reference/")) {
            return Layer.REFERENCE;
        }
        if (internalType.startsWith(CR3_INTERNAL_PREFIX + "research/")) {
            return Layer.RESEARCH;
        }
        return null;
    }

    private enum Layer {
        CONTAINER,
        METADATA,
        CODEC,
        PROCESSING,
        CORE,
        IMAGEIO,
        CLI,
        REFERENCE,
        RESEARCH
    }

    private record ModuleContract(
            String artifactId,
            Class<?> anchor,
            Set<Layer> ownedLayers,
            Set<Layer> allowedReferenceLayers,
            Set<String> explicitlyOwnedTypes) {

        private ModuleContract {
            Objects.requireNonNull(artifactId, "artifactId");
            Objects.requireNonNull(anchor, "anchor");
            ownedLayers = Set.copyOf(ownedLayers);
            allowedReferenceLayers = Set.copyOf(allowedReferenceLayers);
            explicitlyOwnedTypes = Set.copyOf(explicitlyOwnedTypes);
        }
    }
}
